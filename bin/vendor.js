#!/usr/bin/env node
'use strict';
/**
 * vendor.js — generate the copies of the libraries that the skill injects (Tier 2).
 *
 *   node bin/vendor.js           # rebuild every asset from src/
 *   node bin/vendor.js --check   # fail if any asset is stale (run this in CI)
 *
 * WHY. The skill must never fetch code over the network — that shape gets refused by safety
 * classifiers, correctly, because a mutable `main` means what executes is not knowable at review
 * time. So the fallback path injects a LOCAL copy instead. A local copy that can silently drift
 * from src/ is its own trap, which is what `--check` is for.
 *
 * The transform is deliberately dull: drop whole-line comments and blank lines, nothing else. No
 * identifier mangling, no expression rewriting. This file is executed verbatim inside a page, so
 * a clever minifier's bug would surface as wrong prices rather than as a crash. The saving is
 * real anyway, because the sources carry a lot of prose about why Amazon's and eBay's DOMs are
 * the way they are.
 *
 * Any line whose trimmed form starts with `//` is dropped, so never begin a line of real code
 * with a string literal containing a bare `//`. `node --check` and tests/vendor.test.js both run
 * against the output, so a mistake here fails the suite rather than reaching a page.
 *
 * ONE TARGET PER SITE, and that is deliberate. A combined library would double what Tier 2 costs
 * on every injection — the Amazon half would carry eBay's selectors into every amazon.com page it
 * is injected into, and vice versa, for code that `@match` guarantees can never run there. The
 * shared util block is duplicated across the sources instead, with tests/core-parity.test.js
 * holding the two copies byte-identical.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SKILL = path.join(ROOT, '.claude', 'skills', 'shopping-research');

/** Every userscript that gets a vendored twin. Add a site by adding a row. */
const TARGETS = [
  {
    name: 'amzx',
    global: '__amzx',
    src: path.join(ROOT, 'src', 'amazon-claude-bridge.user.js'),
    out: path.join(SKILL, 'assets', 'amzx.min.js'),
  },
  {
    name: 'ebayx',
    global: '__ebayx',
    src: path.join(ROOT, 'src', 'ebay-claude-bridge.user.js'),
    out: path.join(SKILL, 'assets', 'ebayx.min.js'),
  },
];

function build(source, srcName) {
  const body = source
    .split('\n')
    .filter((line) => {
      const t = line.trim();
      return t !== '' && !t.startsWith('//');
    })
    .join('\n');
  return '/* Generated by bin/vendor.js from src/' + (srcName || '') + ' — do not edit. */\n'
    + body + '\n';
}

const rel = (p) => path.relative(ROOT, p).replace(/\\/g, '/');
const kb = (n) => (n / 1024).toFixed(1) + ' KB';

// Guarded: tests/vendor.test.js requires this file for build(), and an unguarded main would
// REBUILD the assets on require — so the staleness check would silently pass every time by
// regenerating the very thing it was supposed to be auditing.
function main() {
  const check = process.argv.includes('--check');
  let stale = 0;

  for (const t of TARGETS) {
    if (!fs.existsSync(t.src)) {
      console.error('MISSING SOURCE: ' + rel(t.src));
      process.exit(1);
    }
    const built = build(fs.readFileSync(t.src, 'utf8'), path.basename(t.src));

    if (check) {
      const current = fs.existsSync(t.out) ? fs.readFileSync(t.out, 'utf8') : null;
      if (current !== built) {
        console.error('STALE: ' + rel(t.out) + ' does not match ' + rel(t.src));
        stale++;
      }
    } else {
      fs.mkdirSync(path.dirname(t.out), { recursive: true });
      fs.writeFileSync(t.out, built, 'utf8');
      console.log('wrote ' + rel(t.out));
      console.log('  source ' + kb(fs.statSync(t.src).size) + ' -> vendored '
        + kb(Buffer.byteLength(built)));
    }
  }

  if (check) {
    if (stale) {
      console.error('\n' + stale + ' stale asset(s). Run: node bin/vendor.js');
      process.exit(1);
    }
    console.log('all ' + TARGETS.length + ' vendored assets are in sync with src/');
  } else {
    console.log('  each is spent in context on every page it is injected into — Tier 1 stays preferred.');
  }
}

if (require.main === module) main();

module.exports = { build, TARGETS, ROOT, SKILL };
